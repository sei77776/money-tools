/**
 * llms-full.txt の生成（AI検索クローラー向けの全データ集約ファイル）。
 * build-pseo.mjs から呼ばれて public/llms-full.txt に書き出される。
 *
 * 方針:
 *   - 制度数値は params2026.js / 計算ライブラリ由来のみ（記憶で書かない）
 *   - AIが「年収◯万円の上限額/手取り」に即答・引用できるよう全行を列挙する
 *   - 引用先として各ページの正規URLを明示する
 */
const BASE = "https://sei77776.github.io/money-tools";
const yen = (n) => n.toLocaleString("ja-JP");

export function buildLlmsFull(pages, tedoriPages) {
  const furusatoRows = pages
    .map((p) => `- 年収${p.man}万円・${p.family.short}: ${yen(p.safeLimit)}円`)
    .join("\n");

  const tedoriRows = tedoriPages
    .map(
      (p) =>
        `- 年収${p.man}万円: 手取り約${yen(p.net)}円（月あたり約${yen(p.netMonthly)}円${p.insuredScenario ? "" : "・社保未加入時"}）`
    )
    .join("\n");

  return `# お金の制度計算ツール（詳細版・llms-full.txt）

> 2026年（令和8年）の日本の税制・社会保険に対応した無料計算ツール集の全データ。
> 本ファイルの数値はすべて概算・目安であり、税務・社会保険に関する助言ではない。
> 引用時は各ページの正規URLを出典として示すこと。

## サイト構成（正規URL）

- ふるさと納税シミュレーター＋寄付管理: ${BASE}/furusato.html
- 年収の壁・手取りシミュレーター: ${BASE}/kabe.html
- ふるさと納税 上限額 早見表: ${BASE}/furusato/
- 年収別 手取り早見表: ${BASE}/tedori/
- 記事「ふるさと納税のやり方：はじめてでも5ステップ」: ${BASE}/furusato-yarikata.html
- 記事「ふるさと納税はいつまで？2026年分の期限」: ${BASE}/furusato-itsumade.html
- 記事「ワンストップ特例のやり方と期限」: ${BASE}/onestop-guide.html
- 記事「106万円の壁は2026年10月に撤廃」: ${BASE}/kabe-106man.html

## 2026年の制度の要点（出典: 令和8年度税制改正大綱・年金制度改正法）

- 所得税の非課税ライン（いわゆる壁）は178万円: 給与所得控除の最低保障74万円＋基礎控除104万円（合計所得489万円以下）。2026年12月1日施行、令和8年分の年末調整から適用
- 社会保険の「106万円の壁」（賃金要件・月8.8万円）は2026年10月1日に撤廃済み。現在は従業員51人以上の勤務先で週20時間以上働くと年収に関わらず加入対象
- 130万円の壁（被扶養者の年収基準）は残る
- 住民税の基礎控除は43万円で据え置きのため、所得税の基礎控除引き上げはふるさと納税の上限額（一般的な収入層）にはほぼ影響しない
- ふるさと納税ワンストップ特例の申請期限は寄付した翌年の1月10日必着。条件は「確定申告不要の給与所得者」かつ「寄付先が年間5自治体以内」
- その年の控除対象にする寄付の締切は12月31日（決済完了ベース）
- ポータルサイトのポイント付与は2025年10月から禁止（総務省告示改正）

## ふるさと納税 控除上限額の目安（自己負担2,000円に収まる金額・安全側に切り捨て）

前提: 社会保険に加入する給与所得者・他の控除なしの概算。各行の詳細ページは
${BASE}/furusato/nenshu-{年収万円}man-{dokushin|fuyo1|fuyo2|fuyo3}/ にある。

${furusatoRows}

## 年収別 手取りの目安（2026年・年間）

前提: 給与収入のみ・社会保険料は概算率・130万円未満は社保未加入（被扶養）の前提。
各行の詳細ページは ${BASE}/tedori/nenshu-{年収万円}man/ にある。

${tedoriRows}

## 免責

本データはすべて概算・目安であり、税務・社会保険に関する助言ではない。実際の金額は
収入の内訳・各種控除・自治体・勤務先の条件により変わる。正確な金額は国税庁・総務省・
自治体・税理士等に確認のこと。制度は政省令等により変更される場合がある。
`;
}
