/**
 * 貼り付けられた値をリンクURLに正規化する。
 * - 素のURL: そのまま（前後の空白は除去）
 * - 楽天が発行するHTMLソース: 最初の href を抽出
 * - プロトコル相対（//で始まる）: https: を補う
 * - http/https 以外のスキーム: 空文字（javascript: 等の混入を防ぐ）
 */
export function normalizeLink(input) {
  const raw = String(input ?? "").trim();
  if (!raw) return "";

  const href = raw.match(/href\s*=\s*["']([^"']+)["']/i)?.[1]?.trim() ?? raw;
  const url = href.startsWith("//") ? `https:${href}` : href;

  return /^https?:\/\//i.test(url) ? url : "";
}

/** url が設定されているオファーだけを、正規化済みURLで返す */
export function activeOffers(offers) {
  return (offers ?? [])
    .map((o) => ({ ...o, url: normalizeLink(o.url) }))
    .filter((o) => o.url.length > 0);
}

/** 表示すべきオファーが1件以上あるか */
export function isEnabled(offers) {
  return activeOffers(offers).length > 0;
}
